from user.models import User
from affiliate.authentication import AffiliateTokenAuthentication
from affiliate.permissions import IsAffiliate
from rest_framework.views import APIView
from rest_framework.response import Response
from rest_framework import status
from affiliate.utils.compute import compute_referral_data
from drf_yasg.utils import swagger_auto_schema
from drf_yasg import openapi


class GetReferrals(APIView):
    authentication_classes = [AffiliateTokenAuthentication,]
    permission_classes = [IsAffiliate,]

    @swagger_auto_schema(
        operation_description='GET Referrals of an affiliate partner',
        operation_summary='This endpoints fetches all referrals belonging to an affiliate user',
        tags=['Affiliate'],
        responses = {
            '200': openapi.Response(
                description='Referrals information',
                schema = openapi.Schema(
                type=openapi.TYPE_OBJECT,
                properties={
                    'msg': openapi.Schema(type=openapi.TYPE_OBJECT,
                        properties={
                            "total_businesses": openapi.Schema(type=openapi.TYPE_INTEGER, description='total businesses invited by an affiliate'),
                            "total_tracking_numbers": openapi.Schema(type=openapi.TYPE_INTEGER, description='total tracking numbers generated by the businesses linked to the affiliate'),
                            "total_coins_earned": openapi.Schema(type=openapi.TYPE_INTEGER, description='total coined earned from total tracking numbers'),
                            "available_coins": openapi.Schema(type=openapi.TYPE_INTEGER, description='total coined left after withdrawal'),
                            "pending_withdrawal": openapi.Schema(type=openapi.TYPE_BOOLEAN, description='true or false'),
                            "referrals": openapi.Schema(type=openapi.TYPE_ARRAY,
                                items={
                                    'business_name': openapi.Schema(type=openapi.TYPE_STRING, description='business name'),
                                    'tracking_numbers': openapi.Schema(type=openapi.TYPE_STRING, description='total tracking numbers generated by this business'),
                                    'total_earned': openapi.Schema(type=openapi.TYPE_STRING, description='total coins earned from this business'),
                                    'country': openapi.Schema(type=openapi.TYPE_STRING, description='country of business'),
                                    'status': openapi.Schema(type=openapi.TYPE_STRING, description='status of the business (active | inactive)')
                                    }
                                )
                            }),
                    },
                example={
                    "total_businesses": 12,
                    "total_tracking_numbers": 75,
                    "total_coins_earned": 750,
                    "available_coins": 750,
                    "pending_withdrawal": False,
                    "referrals": [{
                        'business_name': 'Microsoft',
                        'tracking_numbers': 45,
                        "total_earned": 450,
                        "country": 'Nigeria',
                        "status": "active"
                        }]
                    }
                ),
                ),
            '400': openapi.Response(
                description='Bad Request',
                schema = openapi.Schema(
                    type=openapi.TYPE_OBJECT,
                    properties={
                        'msg': openapi.Schema(type=openapi.TYPE_STRING, description="Error description"
                            )
                        },
                    example = {
                        'msg': "email is required"
                        }
                    ))
            ,

            '401': openapi.Response(
                description='Error: Unauthorized',
                schema = openapi.Schema(
                    type=openapi.TYPE_OBJECT,
                    properties={
                        'detail': openapi.Schema(type=openapi.TYPE_INTEGER, description='Authentication credentials were not provided.')
                        },
                example={
                    'detail': 'Authentication credentials were not provided.'
                    }
                )
            ),

            '403': openapi.Response(
                description='Error: Forbidden',
                schema = openapi.Schema(
                    type=openapi.TYPE_OBJECT,
                    properties={
                        'error': openapi.Schema(type=openapi.TYPE_INTEGER, description='forbidden')
                        },
                    example={
                        'error': 'forbidden'
                        }
                    )
                ),
            })


    def get(self, request):
        
        referral_code = request.user.referral_code
        try:
            affiliated_business=User.objects.filter(
                referral_code=referral_code.lower(),
                account_type='business'
                    )

            data = {
                "total_businesses": len(affiliated_business),
                "total_tracking_numbers": 0,
                "total_coins_earned": 0,
                "available_coins": 0,
                "referrals": [],
                "pending_withdrawal": False
                    }

            if len(affiliated_business) == 0:
                return Response({'msg': data}, status=status.HTTP_200_OK)

            computed_data = compute_referral_data(businesses=affiliated_business, data=data, user=request.user)
            
            if computed_data:
                return Response({'msg': computed_data}, status=status.HTTP_200_OK)
        except Exception as e:
            raise e
